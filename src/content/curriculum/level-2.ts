/**
 * Level 2 — Guitar fundamentals. String index in visuals: 0 = low E (6th string) … 5 = high E (1st string).
 */

/** Builds one "meet a string" lesson: open note + first frets, with an exercise for that string. */
function stringLesson(opts: {
  id: string;
  order: number;
  prereq: string;
  number: number;
  index: number;
  name: string;
  open: string;
  notes: { fret: number; note: string }[];
  tip: string;
  hinglish: string;
  quiz: ReturnType<typeof q>[];
}): Lesson {
  const seq = opts.notes.map((n) => n.note);
  return {
    id: opts.id,
    track: "guitar",
    level: 2,
    order: opts.order,
    title: `String ${opts.number}: the ${opts.name} string`,
    summary: `Meet string ${opts.number} (${opts.open}) and its first notes: ${opts.notes.map((n) => n.note.replace(/\d/, "")).join(", ")}.`,
    minutes: 6,
    skills: ["guitar-strings", "fretboard-notes", `string-${opts.number}`],
    prerequisites: [opts.prereq],
    topics: ["guitar-beginner", "notes-and-scales"],
    steps: [
      {
        id: "meet",
        kind: "visual",
        title: `String ${opts.number} — ${opts.open}`,
        body: `String **${opts.number}** is tuned to **${opts.open}**. ${opts.tip}\n\nThe notes we'll play on it: ${opts.notes.map((n) => `**${n.note.replace(/\d/, "")}** (${n.fret === 0 ? "open" : `fret ${n.fret}`})`).join(", ")}.`,
        hinglish: opts.hinglish,
        visual: { type: "fretboard", frets: 5, highlight: opts.notes.map((n) => ({ string: opts.index, fret: n.fret, label: n.note.replace(/\d/, "") })) },
      },
      {
        id: "hear",
        kind: "listen",
        title: "Hear the notes",
        body: "Listen up and back down.",
        audio: { type: "notes", notes: [...seq, ...seq.slice(0, -1).reverse()], step: 0.6, instrument: "guitar" },
      },
      {
        id: "tab",
        kind: "visual",
        title: "In tab",
        body: "The same notes written as tablature: each number is a fret on this string.",
        visual: { type: "tab", lines: tabFor(opts.index, opts.notes.map((n) => n.fret)) },
      },
      {
        id: "play",
        kind: "exercise",
        title: "Play them in order",
        body: "Use the virtual fretboard, or your real guitar with the microphone on. On a real guitar, press just behind the fret with your fingertip.",
        exercise: { type: "play-sequence", instrument: "guitar", notes: seq, prompt: `Play ${seq.map((s) => s.replace(/\d/, "")).join(" – ")} on string ${opts.number}.`, fingers: opts.notes.map((n) => (n.fret === 0 ? 0 : Math.min(n.fret, 4))) },
        mastery: true,
        passAccuracy: 0.75,
      },
      {
        id: "mic",
        kind: "exercise",
        title: "Real guitar: the open string",
        body: `Pluck the open ${opts.open} string on your guitar and let it ring. If it's out of tune we'll tell you whether it's high or low (tune it in the [Tuner](/tuner)).`,
        exercise: { type: "mic-note", instrument: "guitar", note: opts.open, prompt: `Pluck open string ${opts.number} (${opts.open}).` },
      },
    ],
    quiz: opts.quiz,
    passScore: 0.67,
  };
}

/** Six-line tab for single notes on one string. */
function tabFor(stringIndex: number, frets: number[]): string[] {
  const names = ["e", "B", "G", "D", "A", "E"]; // top line = high e
  return names.map((n, line) => {
    const s = 5 - line;
    const cells = frets.map((f) => (s === stringIndex ? String(f).padEnd(2, "-") : "--"));
    return `${n}|-${cells.join("-")}-|`;
  });
}

